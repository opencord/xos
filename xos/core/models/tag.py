
from header import *





from core.models.service import Service 



from core.models.contenttype import ContentType 






class Tag(PlCoreBase):
  # Primitive Fields (Not Relations)
  name = CharField( help_text = "The name of this tag", max_length = 128, null = False, db_index = True, blank = False )
  value = StrippedCharField( help_text = "The value of this tag", max_length = 1024, null = False, db_index = False, blank = False )
  object_id = IntegerField( blank = False, null = False, db_index = False )
  

  # Relations
  
  service = ForeignKey(Service, help_text = "The Service this Tag is associated with", related_name = 'tags', null = False, db_index = True, blank = False )
  content_type = ForeignKey(ContentType, db_index = True, related_name = 'tag', null = False, blank = False )

  content_object = GenericForeignKey('content_type', 'object_id') # Not generated by xproto
  
  def __unicode__(self):
      return self.name
  
  def can_update(self, user):
      return user.can_update_root()
  
  @classmethod
  def select_by_content_object(cls, obj):
      return cls.objects.filter(content_type=ContentType.objects.get_for_model(obj), object_id=obj.id)
  
  @staticmethod
  def select_by_user(user):
      return Tag.objects.all()
  pass

