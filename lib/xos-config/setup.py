#!/usr/bin/env python

import os

from setuptools import setup

# If we're running setup.py within the build system, then autogenerate version.py

file_path = os.path.abspath(os.path.dirname(os.path.realpath(__file__)))
version_filename = os.path.join(file_path, "VERSION")
if not os.path.exists(version_filename):
    version_filename = os.path.join(file_path, "../../VERSION")
if os.path.exists(version_filename):
    version = open(version_filename, "rt").readline().strip()
    f = open(os.path.join(file_path, "xosconfig", "version.py"),"wt")
    f.write("# this file is autogenerated. Do not edit\n")
    f.write("__version__ = '%s'\n" % version)
    f.close()

from xosconfig.version import __version__

setup(name='XosConfig',
      version=__version__,
      description='XOS Config Library',
      author='Matteo Scandolo',
      author_email='teo@onlab.us',
      packages=['xosconfig'],
      include_package_data=True
     )
