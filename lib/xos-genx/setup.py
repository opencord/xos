def setup_with_auto_version(*args, **kwargs):
    import inspect
    from xosutil.autodiscover_version import autodiscover_version

    frame = inspect.stack()[1]
    caller_module = inspect.getmodule(frame[0])
    version = autodiscover_version(caller_filename = caller_module.__file__)
    if version:
        kwargs["version"] = version

    cmdclass = {"sdist": SdistCommand,
                "build_py": BuildPyCommand,
                "bdist_egg": BdistEggCommand,
                "install": InstallCommand}
    kwargs["cmdclass"] = cmdclass

    setup(*args, **kwargs)

